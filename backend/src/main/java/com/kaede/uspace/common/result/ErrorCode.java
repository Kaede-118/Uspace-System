package com.kaede.uspace.common.result;

import org.springframework.http.HttpStatus;

/**
 * 业务错误码。
 *
 * <p>每个枚举项携带三样东西：<b>HTTP 状态码</b>（给浏览器、代理与网关看）、
 * <b>业务码</b>（给前端判断分支用）、<b>中文消息</b>（默认展示文案）。
 *
 * <p>业务码取五位，前三位与 HTTP 状态码对齐（如 {@code 40901} 对应 409）。
 * 这样从日志里扫一眼业务码就知道大概是什么性质的问题，不必回查对照表。
 *
 * <p><b>为什么 HTTP 状态码与业务码都要有</b>：两者粒度不同，缺一不可。
 * HTTP 状态码是公开的、粗粒度的语义 —— 代理、网关、浏览器都认它，
 * 前端 axios 拦截器也靠它统一处理「登录态失效」；
 * 业务码则是细粒度的，用来区分「同样是 401，到底是没带 token、
 * token 过期，还是改密后被撤销了」。只留一个都不够用。
 *
 * <p>新增错误码时请保持两件事：业务码不与既有值重复；HTTP 状态码选语义最贴近的那个，
 * 不要一律用 500 —— 那会让「服务端出错」与「用户操作不当」在监控里无从区分。
 */
public enum ErrorCode {

    // ------------------------------------------------------------------
    // 400：请求本身有问题，改请求即可成功
    // ------------------------------------------------------------------

    /** 请求参数不合法：校验未通过、格式错误、类型不匹配 */
    PARAM_INVALID(HttpStatus.BAD_REQUEST, 40000, "请求参数不合法"),

    /**
     * 上传的文件不是受支持的图片。
     *
     * <p>三种情形共用本码：没选文件、文件是空的、以及文件的<b>真实内容</b>
     * 不是 JPG / PNG / WebP。具体是哪种靠 {@code BizResult} 的附加消息区分 ——
     * 对用户而言处置动作相同（重新选一张图）。
     *
     * <p><b>判类型看的是文件头（magic bytes）而不是 {@code Content-Type}</b>：
     * 后者是客户端自己说的，能随便伪造 —— 把 {@code evil.jsp} 的
     * {@code Content-Type} 写成 {@code image/png} 就能骗过去。
     */
    UPLOAD_FILE_INVALID(HttpStatus.BAD_REQUEST, 40001, "只支持 JPG、PNG、WebP 格式的图片"),

    // ------------------------------------------------------------------
    // 401：身份未确认（没登录、凭证无效或过期）
    // ------------------------------------------------------------------

    /** 未携带认证凭证 */
    UNAUTHORIZED(HttpStatus.UNAUTHORIZED, 40100, "请先登录"),

    /**
     * 凭证无效：签名错误、格式错误，或因改密 / 封禁导致版本号对不上而被撤销。
     *
     * <p>刻意把「凭证损坏」与「凭证被撤销」合并成一个码：
     * 对用户而言两种情况的处置完全相同（重新登录），分开只会把内部机制暴露给前端。
     */
    TOKEN_INVALID(HttpStatus.UNAUTHORIZED, 40101, "登录状态已失效，请重新登录"),

    /** 凭证已过期 */
    TOKEN_EXPIRED(HttpStatus.UNAUTHORIZED, 40102, "登录已过期，请重新登录"),

    /**
     * 用户名或密码错误。
     *
     * <p><b>「用户不存在」也复用这个码</b>，不单独给一个 USER_NOT_FOUND ——
     * 否则攻击者可以靠错误码的差异枚举出系统里有哪些用户名。
     */
    BAD_CREDENTIALS(HttpStatus.UNAUTHORIZED, 40103, "用户名或密码错误"),

    // ------------------------------------------------------------------
    // 403：身份已确认，但没资格做这件事
    // ------------------------------------------------------------------

    /** 已登录，但当前角色不具备该操作的权限 */
    FORBIDDEN(HttpStatus.FORBIDDEN, 40300, "没有操作权限"),

    /**
     * 账号已被禁用。
     *
     * <p>用 403 而非 401：401 的语义是「你是谁不清楚」，
     * 而这里是「知道你是谁，但你不能进」—— 两者的前端处置也不同
     * （前者跳登录页，后者应提示联系管理员）。
     */
    ACCOUNT_DISABLED(HttpStatus.FORBIDDEN, 40301, "账号已被禁用，请联系管理员"),

    // ------------------------------------------------------------------
    // 404：资源不存在
    // ------------------------------------------------------------------

    /** 请求的资源不存在（含未匹配到任何接口的路径） */
    NOT_FOUND(HttpStatus.NOT_FOUND, 40400, "请求的资源不存在"),

    /** 目标用户不存在（或已被逻辑删除） */
    USER_NOT_FOUND(HttpStatus.NOT_FOUND, 40401, "用户不存在"),

    /** 门店不存在。通常是没执行建表脚本，或门店记录被误删 */
    STORE_NOT_FOUND(HttpStatus.NOT_FOUND, 40402, "门店不存在"),

    /** 停业记录不存在（或已被逻辑删除） */
    CLOSURE_NOT_FOUND(HttpStatus.NOT_FOUND, 40403, "停业记录不存在"),

    /** 包场记录不存在（或已被逻辑删除） */
    BOOKING_NOT_FOUND(HttpStatus.NOT_FOUND, 40404, "包场记录不存在"),

    // --- 模块 8 订单管理 ---

    /**
     * 订单不存在（或已被逻辑删除）。
     *
     * <p><b>查询他人的订单时也返回本码</b>，而不是 403 —— 403 等于承认「这个订单存在，
     * 只是不归你」，攻击者可以靠状态码的差异枚举出系统里有哪些订单号。
     */
    ORDER_NOT_FOUND(HttpStatus.NOT_FOUND, 40405, "订单不存在"),

    /**
     * 门店尚未配置智能门锁。
     *
     * <p>下单要下发限时密码，而密码的入参是 {@code lockId}；门锁表为空时取不到，
     * 整条主链路在第一步就断掉。与 {@link #STORE_NOT_FOUND} 同属「系统未初始化」——
     * 两者的解法也一样：去执行建表脚本。所以共用 404 段。
     */
    LOCK_NOT_CONFIGURED(HttpStatus.NOT_FOUND, 40406, "门店门锁未就绪，请联系管理员"),

    /**
     * 月卡（或月卡购买单）不存在。
     *
     * <p>与 {@link #ORDER_NOT_FOUND} 同理：<b>操作他人的月卡也返回本码</b>，
     * 而不是 403 —— 403 等于承认「这个卡存在，只是不归你」，
     * 可以被用来枚举卡号。
     */
    CARD_NOT_FOUND(HttpStatus.NOT_FOUND, 40407, "月卡不存在"),

    // --- 模块 4 设备管理 ---

    /** 机台不存在（或已逻辑删除，如机器已退役） */
    DEVICE_NOT_FOUND(HttpStatus.NOT_FOUND, 40408, "机台不存在"),

    /**
     * 设备类型不存在。
     *
     * <p>录入机台时 {@code typeId} 指向了字典表里没有的取值。
     * 与 {@link #LOCK_NOT_CONFIGURED} 的区别是：那个是「系统没配好」，
     * 这个是「调用方给错了」—— 前端下拉框的数据过期时就会撞上。
     */
    EQUIPMENT_TYPE_NOT_FOUND(HttpStatus.NOT_FOUND, 40409, "设备类型不存在"),

    // --- 公告模块 ---

    /**
     * 公告不存在。
     *
     * <p>同 {@link #ORDER_NOT_FOUND} 与 {@link #CARD_NOT_FOUND} 的做法：
     * <b>后台改一条不属于自己的东西也返回本码</b>，不额外造一个 403 ——
     * 不过公告与订单不同，它本来就是全员可见的，这里返回 404 只是「这条记录没了」
     * 这一个含义（被别的管理员删掉、或 ID 传错了）。
     */
    NOTICE_NOT_FOUND(HttpStatus.NOT_FOUND, 40410, "公告不存在"),

    // --- 商品包 ---

    /**
     * 商品不存在（或已逻辑删除）。
     *
     * <p>与 {@link #ORDER_NOT_FOUND} 同一套做法：把「不存在」与「已下架」
     * 分开成两个码，因为用户的可行动作不同 —— 前者是「这个链接过期了」，
     * 后者是「换个东西买」。而「不归你」这类判断仍走本码，
     * 不用 403，免得被用来枚举 ID。
     */
    PRODUCT_NOT_FOUND(HttpStatus.NOT_FOUND, 40411, "商品不存在"),

    /**
     * 商品购买单不存在（或不属于当前用户）。
     *
     * <p>与 {@link #CARD_NOT_FOUND} 同理：<b>操作他人的购买单也返回本码</b>，
     * 而不是 403 —— 403 等于承认「这个单子存在，只是不归你」，
     * 可以被用来枚举单号。
     */
    PRODUCT_ORDER_NOT_FOUND(HttpStatus.NOT_FOUND, 40412, "商品订单不存在"),

    // ------------------------------------------------------------------
    // 409：请求合法，但与当前数据状态冲突
    // ------------------------------------------------------------------

    /** 业务冲突兜底。各模块若没有更贴切的码，用它 */
    BUSINESS_REJECTED(HttpStatus.CONFLICT, 40900, "当前状态不允许该操作"),

    /** 用户名已被占用 */
    USERNAME_EXISTS(HttpStatus.CONFLICT, 40901, "该用户名已被使用"),

    /** QQ 号已被其他账号绑定。模块 11 靠 QQ 号定位用户，重号会让查询结果不确定 */
    QQ_ALREADY_BOUND(HttpStatus.CONFLICT, 40902, "该 QQ 号已被其他账号绑定"),

    /** 修改密码时原密码不正确 */
    OLD_PASSWORD_MISMATCH(HttpStatus.CONFLICT, 40903, "原密码不正确"),

    /** 新密码与原密码相同 */
    PASSWORD_UNCHANGED(HttpStatus.CONFLICT, 40904, "新密码不能与原密码相同"),

    /** 管理员不能对自己执行封禁、改角色一类的操作 */
    SELF_OPERATION_FORBIDDEN(HttpStatus.CONFLICT, 40905, "不能对自己执行该操作"),

    /** 角色取值不在允许范围内 */
    ROLE_INVALID(HttpStatus.CONFLICT, 40906, "角色取值不合法"),

    // --- 模块 3 空间管理 ---

    /** 门店名称已被占用。库里有唯一索引 {@code uk_name} 兜底 */
    STORE_NAME_EXISTS(HttpStatus.CONFLICT, 40907, "该门店名称已被使用"),

    /** 停业时段的首尾颠倒 */
    CLOSURE_TIME_INVALID(HttpStatus.CONFLICT, 40908, "停业结束时间必须晚于开始时间"),

    /** 停业时段与既有记录重叠 */
    CLOSURE_OVERLAP(HttpStatus.CONFLICT, 40909, "该时段已有停业记录，请调整或合并"),

    /** 包场时段的首尾颠倒 */
    BOOKING_TIME_INVALID(HttpStatus.CONFLICT, 40910, "包场结束时间必须晚于开始时间"),

    /** 包场开始时间早于当前时刻 */
    BOOKING_START_IN_PAST(HttpStatus.CONFLICT, 40911, "包场开始时间不能早于当前时刻"),

    /** 包场时段与既有包场重叠 */
    BOOKING_OVERLAP(HttpStatus.CONFLICT, 40912, "该时段已有其他包场"),

    /** 包场时段与停业时段重叠 */
    BOOKING_CLOSURE_OVERLAP(HttpStatus.CONFLICT, 40913, "该时段已安排停业，不能排包场"),

    /** 当前状态不允许修改或取消包场（只有待付款的可以） */
    BOOKING_NOT_EDITABLE(HttpStatus.CONFLICT, 40914, "只有待付款的包场可以修改或取消"),

    /**
     * 门店正在停业，拒绝新下单。
     *
     * <p>供模块 8 的下单校验使用 —— 模块 3 只提供「此刻是否停业」的判断
     * （见 {@code ClosureService#isClosedAt}），拒绝的动作发生在下单链路上。
     */
    STORE_CLOSED(HttpStatus.CONFLICT, 40915, "当前暂停营业，暂不支持下单"),

    // --- 模块 6 进出记录 ---

    /**
     * 开门记录的时间参数不合法。
     *
     * <p>三种情形共用本码，靠 {@code BizResult} 的附加消息区分：
     * 同步区间首尾颠倒、单次同步跨度超过 31 天、补录的开门时刻落在未来。
     * 不为「跨度太大」单开一个码 —— 对调用方而言处置动作完全相同（改参数重试）。
     */
    ACCESS_TIME_INVALID(HttpStatus.CONFLICT, 40916, "开门记录的时间不合法"),

    // --- 模块 8 订单管理 ---

    /**
     * 该时段已被包场，且请求者既不是包场人、也未携带有效的邀请令牌。
     *
     * <p>这是「停业 → 包场 → 普通」三层准入判断里的第二层。准入的落地方式是
     * <b>不下发密码</b>而非门锁黑名单 —— 拿不到密码自然进不去。
     */
    BOOKING_ACCESS_DENIED(HttpStatus.CONFLICT, 40917, "该时段已被包场，仅限包场人与被邀请者进入"),

    /**
     * 包场开始前的「预备窗口」内，任何人都不再放行。
     *
     * <p>包场开始前若干分钟起就停止接待新顾客 —— 一局游戏打不完就要被清场，
     * 放进来等于让顾客花了钱却玩不尽兴。这段时间是留给店内散客自然离场的缓冲。
     *
     * <p>窗口长度是配置项，提示语里要写出具体分钟数时由 Service 层拼装，
     * 不要把这个码的文案当成可变数字的载体。
     */
    BOOKING_PREPARING(HttpStatus.CONFLICT, 40922, "包场即将开始，暂停接待新顾客"),

    /**
     * 包场开始前，参与者到得太早。
     *
     * <p>包场人与被邀请者可以比普通顾客早入场（提前量是配置项），
     * 但也不能无限早 —— 包场时段开始前店里还按普通营业安排。
     * 与 {@link #BOOKING_PREPARING} 的区别在于「对谁」：那条挡的是所有人，
     * 这条只挡参与者，且是「再等等就行」而非「今天进不去」。
     */
    BOOKING_NOT_STARTED(HttpStatus.CONFLICT, 40923, "包场尚未开始，参与者暂不能入场"),

    /**
     * 订单当前状态不支持该操作。
     *
     * <p>「结束使用」只认 {@code IN_USE}、「查看密码」只认 {@code IN_USE}……
     * 具体是哪一种情形，靠 {@code BizResult} 的附加消息区分 ——
     * 与 {@link #ACCESS_TIME_INVALID} 同一套做法：对调用方而言处置动作相同。
     */
    ORDER_STATUS_INVALID(HttpStatus.CONFLICT, 40918, "当前订单状态不支持该操作"),

    /**
     * 该用户已有进行中的订单。
     *
     * <p><b>这道校验挡的是「连点两下开门」</b>：点一次开门就会创建订单并开始计费，
     * 少了它，手指抖一下就会产生两个密码、两条并行计费的订单，用户要付两份钱。
     */
    ORDER_ALREADY_ACTIVE(HttpStatus.CONFLICT, 40919, "你有未完成的订单，请先结束该订单"),

    /**
     * 已支付的订单不能调整时长。
     *
     * <p>调整必然改变金额，已入账的订单就要走退款与对账 —— 那是人工运营流程，
     * 本期不实现。允许调整的只有 {@code IN_USE} 与 {@code PENDING_PAYMENT}。
     */
    ORDER_NOT_ADJUSTABLE(HttpStatus.CONFLICT, 40920, "已支付的订单不能调整时长，退款请走人工流程"),

    /** 人工核销时订单尚未提交支付凭证 —— 没有核销依据 */
    PAYMENT_PROOF_REQUIRED(HttpStatus.CONFLICT, 40921, "该订单尚未提交支付凭证，不能核销"),

    // --- 模块 9 优惠管理 ---

    /**
     * 已有生效中的月卡，不能再买一张。
     *
     * <p>两张时间重叠的卡不会带来任何额外权益（免单时段是同一批时段），
     * 只会让「哪张在生效」变得不确定，退起款来也说不清该退哪张。
     * 续费的时机是<b>旧卡到期之后</b>，那时本码不再拦。
     *
     * <p>具体是哪张卡、到哪天为止，由 Service 层拼进附加消息。
     */
    CARD_ALREADY_ACTIVE(HttpStatus.CONFLICT, 40924, "你已有生效中的月卡，到期后可再次购买"),

    /**
     * 有一笔未完成的月卡购买单。
     *
     * <p>挡的是「反复点购买、留下一堆待支付单」——那些单子本身无害，
     * 但用户若把它们都付了款，就会拿到多张重叠的卡。
     *
     * <p>单子超过存活时长后会自动关闭，届时不带附加消息地再试即可；
     * 用户也可以主动取消。
     */
    CARD_PENDING_PAYMENT_EXISTS(HttpStatus.CONFLICT, 40925, "你有一笔待支付的月卡，请先完成支付或取消该笔"),

    /**
     * 月卡当前状态不支持该操作。
     *
     * <p>如「取消一笔已经付过款的购买单」。具体情形靠 {@code BizResult}
     * 的附加消息区分 —— 与 {@link #ORDER_STATUS_INVALID} 同一套做法。
     */
    CARD_STATUS_INVALID(HttpStatus.CONFLICT, 40926, "当前月卡状态不支持该操作"),

    // --- 模块 4 设备管理 ---

    /**
     * 资产编号已被同门店的其他机台占用。
     *
     * <p>库里有唯一索引 {@code uk_store_device_no} 兜底 ——
     * 应用层查重挡不住并发，两个管理员同时录入同一编号时由索引拦下，
     * 全局异常处理器翻译成 409。
     *
     * <p><b>编号为空不算冲突</b>：多台还没贴编号的机器可以共存，
     * MySQL 的唯一索引允许多行为 NULL。
     */
    DEVICE_NO_EXISTS(HttpStatus.CONFLICT, 40927, "该资产编号已被其他机台使用"),

    /**
     * 机台状况取值不合法。
     *
     * <p>与 {@link #ROLE_INVALID} 同一套做法：取值范围的权威定义在
     * {@code DeviceStatus} 枚举里，非法值在落库前拦下 ——
     * 状况列是 {@code VARCHAR} 而非库级 {@code ENUM}，库不会替我们挡住。
     */
    DEVICE_STATUS_INVALID(HttpStatus.CONFLICT, 40928, "机台状况取值不合法"),

    // --- 公告模块 ---

    /**
     * 系统自动发布的公告不能修改或删除。
     *
     * <p><b>为什么单独成一个错误码，而不是并进 {@link #BUSINESS_REJECTED}</b>：
     * 用户的可行动作完全不同 —— 看到这个码，管理员该做的是<b>去改机台状况</b>
     * （那会产生一条新的公告），而不是换个写法再试一次。
     * 给一句笼统的「操作不被允许」，他会以为是权限或时机问题，白试几轮。
     *
     * <p><b>为什么自动公告必须只读</b>：它是<b>已经发生的事实</b>的记录，
     * 改写或删除等于篡改历史。消息流里也没有「下架」这个动作 ——
     * 后面还会有新的消息盖过它。所以这个拒绝不是拦路，而是指出正确的做法。
     */
    NOTICE_AUTO_READONLY(HttpStatus.CONFLICT, 40929, "系统自动发布的公告不能修改或删除，它记录的是已发生的事实"),

    /**
     * 包场尚未付款，取不到邀请链接。
     *
     * <p>邀请令牌与参与者名单都是<b>付款成功那一刻</b>才生成的 ——
     * 未付款的包场既没有令牌可分享，也无从谈起「谁在这场里」。
     *
     * <p><b>为什么不复用 {@link #BOOKING_NOT_EDITABLE}</b>：那个码说的是
     * 「状态不对，不能改也不能取消」，本码说的是「东西还没生成」。
     * 用户看到之后该做的事也不同：一个该去付款，一个该放弃修改。
     * 这与 {@link #ORDER_ALREADY_ACTIVE} / {@link #ORDER_UNPAID_EXISTS}
     * 分成两个码是同一个理由 —— 合并成一个只会得到一句双方都用不上的模糊提示。
     */
    BOOKING_NOT_PAID(HttpStatus.CONFLICT, 40930, "包场尚未付款，付款后才能分享邀请链接"),

    // --- 模块 8 订单管理（续） ---

    /**
     * 该用户有一笔尚未支付的订单，不能再开新单。
     *
     * <p><b>为什么与 {@link #ORDER_ALREADY_ACTIVE} 分成两个码</b>：
     * 两者挡的是不同的场景，用户该做的事也完全不同 ——
     * 看到 {@code ORDER_ALREADY_ACTIVE} 说明人还在店里玩，该去「查看密码」；
     * 看到本码说明人已经玩完了、账单也出来了，该去「去支付」。
     * 合并成一个码的话，前端只能给一句模糊的提示，
     * 而用户不知道该点「结束使用」还是「去支付」—— 这两个动作的后果完全不同。
     *
     * <p><b>这道校验补的是一个既有缺口</b>：早先的防连点只查 {@code IN_USE}，
     * 于是「结算了但不付款」的账号可以再开一单进场，欠着费接着玩。
     * 现在 {@code IN_USE} 与 {@code PENDING_PAYMENT} 一并拦下。
     *
     * <p>注意本码<b>只影响下单</b>：{@code GET /api/orders/current} 仍只返回
     * {@code IN_USE} 的订单 —— 首页靠它决定按钮是「开门」还是「查看密码」，
     * 把已结算的订单塞进去会让用户看到一个「查看密码」，而那时密码早就撤销了。
     *
     * <p>本码取 40931，因为 40930 是 {@link #BOOKING_NOT_PAID}。
     */
    ORDER_UNPAID_EXISTS(HttpStatus.CONFLICT, 40931, "你有一笔未支付的订单，请先完成支付"),

    // --- 商品包 ---

    /**
     * 商品已售罄，或下单数量超过了可售量。
     *
     * <p>两种情形共用本码，靠 {@code BizResult} 的附加消息区分
     * （「已售罄」与「仅剩 N 件」）—— 对用户而言处置动作相同：
     * 少买几件，或者等补货。与 {@link ACCESS_TIME_INVALID} 同一套做法。
     *
     * <p><b>这里说的「可售量」是「库存 − 未支付的待支付单数」</b>，
     * 不是库存本身：别人下了单还没付款的那部分，也算被占着 ——
     * 否则会出现两人同时买最后一件、都下单成功、后付款的那个没货可拿。
     * 这道检查不锁库存，所以仍有竞态窗口，最后一道防线是支付时的
     * 条件 UPDATE（扣不动就转人工处理）。
     */
    PRODUCT_SOLD_OUT(HttpStatus.CONFLICT, 40932, "商品已售罄"),

    /**
     * 商品或商品订单的当前状态不支持该操作。
     *
     * <p>如「对已下架的商品下单」与「取消一笔已经付过款的购买单」。
     * 具体情形靠 {@code BizResult} 的附加消息区分 ——
     * 与 {@link ORDER_STATUS_INVALID}、{@link CARD_STATUS_INVALID} 同一套做法。
     */
    PRODUCT_STATUS_INVALID(HttpStatus.CONFLICT, 40933, "当前商品状态不支持该操作"),

    // ------------------------------------------------------------------
    // 413：请求体太大，服务端拒绝处理
    // ------------------------------------------------------------------

    /**
     * 上传的图片超过大小上限。
     *
     * <p><b>为什么要单开一个码，而不是并进 {@link #PARAM_INVALID}</b>：
     * 用户的可行动作不同。同样是传图失败，「格式不对」要去换一张别的图，
     * 「太大了」只要压缩一下或换张小图就行 —— 给一句笼统的「请求参数不合法」，
     * 他会以为是格式问题白试几轮。
     *
     * <p>这条也是 {@code GlobalExceptionHandler} 里
     * {@code MaxUploadSizeExceededException} 分支的归宿。不加那个分支的话，
     * 超限会落到兜底的 {@code Exception} 返回 500「服务异常，请稍后重试」——
     * 而让用户去重试一件永远不会成功的事，比不提示更糟。
     *
     * <p>大小上限是配置项（{@code uspace.upload.max-image-bytes}），
     * 文案里的「2MB」与它对应；改配置时文案要一起改。
     */
    UPLOAD_FILE_TOO_LARGE(HttpStatus.PAYLOAD_TOO_LARGE, 41300, "图片大小不能超过 2MB"),

    // ------------------------------------------------------------------
    // 500：服务端自身出错，与请求无关
    // ------------------------------------------------------------------

    /**
     * 服务端内部错误兜底。
     *
     * <p>对外只给一句笼统提示，具体堆栈只进服务端日志 ——
     * 异常信息里常含表名、SQL、路径，返回给前端等于免费送情报。
     */
    INTERNAL_ERROR(HttpStatus.INTERNAL_SERVER_ERROR, 50000, "服务异常，请稍后重试"),

    // ------------------------------------------------------------------
    // 502：上游依赖不可用。本服务作为客户端，从上游拿到的是失败或无效响应 ——
    // 与 500 的区别在于「错不在我们」，与 409 的区别在于「不是用户操作不当」。
    // 分开之后，监控上能一眼区分「门锁云挂了」和「用户传错了参数」。
    // ------------------------------------------------------------------

    /**
     * 门锁云调用失败：拉取开门记录无果，或锁状态不可确认。
     *
     * <p><b>为什么用 502 而不是 409</b>：门锁云不可达或拒绝响应，语义上最贴近
     * 502 Bad Gateway（本服务作为上游的客户端，拿到了失败或无效响应）。
     * 挂 409 等于告诉前端与监控「这是业务冲突」，会让真实的故障淹没在业务错误里。
     *
     * <p><b>本码最要紧的用途是「不让失败伪装成空」</b>：通通锁的查询接口失败时
     * 返回空列表而非抛异常，若直接采信就会把「云端没拉到」当成「确实没有开门记录」，
     * 于是计费起点永远取不到、而系统一声不吭。因此同步结果为空时必须再探活一次，
     * 探不出「锁在线」就返回本码，而不是返回一个「成功、0 条」。
     *
     * <p>具体原因是「锁离线」「云端不可达」还是「密码下发被拒」，
     * 靠 {@code BizResult} 的附加消息区分。
     */
    LOCK_CLOUD_UNAVAILABLE(HttpStatus.BAD_GATEWAY, 50200, "门锁云调用失败，请稍后重试"),

    /**
     * 支付网关调用失败：下单、查单或验签未通过。
     *
     * <p>与 {@link #LOCK_CLOUD_UNAVAILABLE} 同属「上游依赖不可用」，但<b>刻意分成两个码</b>：
     * 监控上要能一眼区分「门锁云挂了」和「支付通道挂了」—— 两者的处置动作完全不同
     * （前者找锁商，后者找支付平台），合并成一个码会让真实的故障性质淹没在笼统的 502 里。
     */
    PAYMENT_GATEWAY_UNAVAILABLE(HttpStatus.BAD_GATEWAY, 50201, "支付网关调用失败，请稍后重试");

    /** 对应的 HTTP 状态码 */
    private final HttpStatus httpStatus;

    /** 业务码，五位数字，前三位与 HTTP 状态码对齐 */
    private final int code;

    /** 默认的中文提示文案 */
    private final String message;

    ErrorCode(HttpStatus httpStatus, int code, String message) {
        this.httpStatus = httpStatus;
        this.code = code;
        this.message = message;
    }

    /**
     * 取对应的 HTTP 状态码。
     *
     * @return HTTP 状态码
     */
    public HttpStatus getHttpStatus() {
        return httpStatus;
    }

    /**
     * 取业务码。
     *
     * @return 五位业务码
     */
    public int getCode() {
        return code;
    }

    /**
     * 取默认提示文案。
     *
     * @return 中文提示
     */
    public String getMessage() {
        return message;
    }
}
