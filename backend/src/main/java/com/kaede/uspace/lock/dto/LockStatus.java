package com.kaede.uspace.lock.dto;

/**
 * 智能门锁的在线状态。
 *
 * <p>通通锁的锁以蓝牙为主要通信方式，接入网关或使用 Wi-Fi 锁才能与云端保持连接。
 * 「在线」表示云端可下发指令，「离线」表示指令需等锁重新连接后才能送达。
 */
public enum LockStatus {

    /** 在线：云端可立即下发指令（如远程下发密码） */
    ONLINE,

    /** 离线：云端无法立即下发，指令需排队等待锁重新连接 */
    OFFLINE,

    /** 未知：尚未查询或查询失败 */
    UNKNOWN
}
