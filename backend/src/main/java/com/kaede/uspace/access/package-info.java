/**
 * 进出记录（模块 6）。
 *
 * <p>职责：把门锁产生的开门事件拉到本地库里，并提供查询。
 *
 * <p><b>本包记录的是「开门事件」，而非严格意义上的进与出。</b>封闭空间的出门是机械推杠
 * 或按钮（消防要求内部必须能免密自由开门），<b>不产生门锁记录</b>；用户的离场时刻
 * 由其在应用内点「结束使用」确定，落在 {@code biz_order.end_time}（模块 8）。
 * 因此本表是 append-only 的事件日志：<b>不提供修改与删除接口</b>。
 *
 * <p><b>本包不参与计费链路</b>：计费起点是订单的 {@code start_time}
 * （用户点击「开门」的时刻），由模块 8 自行记录，无需等门锁记录回来对齐时刻。
 * 本包的定位是<b>旁路的记录与审计</b> —— 供人工复核（用户忘记点「结束使用」时
 * 与监控录像比对）、争议追溯，以及 QQ 群播报参考。
 *
 * <p><b>数据来源与调用额度</b>：门锁云不提供开门记录的推送回调，只能主动拉取；
 * 而免费额度 <b>30000 次/月</b>是硬约束。因此 {@code AccessRecordService#syncRecords}
 * 只在管理员点击时触发一次，<b>绝不做定时轮询</b>。上游是
 * {@code com.kaede.uspace.lock.LockService#listRecords}，其失败语义是
 * 「返回空列表」而非抛异常 —— 本包专门做了探活来区分「拉取失败」与「确实没有记录」。
 *
 * <p><b>时间区间口径</b>：本包对外一律半开 {@code [from, to)}，与 {@code space} 包一致；
 * 而上游 {@code listRecords} 是闭区间，多出来的那条由 Service 过滤。
 *
 * <p>对应毕业论文中的「进出记录」章节。
 */
