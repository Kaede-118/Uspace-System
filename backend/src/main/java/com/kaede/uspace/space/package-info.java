/**
 * 空间管理（模块 3）。
 *
 * <p>职责：门店信息、停业时段与包场时段管理。
 *
 * <p>对应毕业论文中的「空间管理」章节。包名沿用论文的模块名，
 * 而实体与表按业务实际叫「门店」（{@code Store} / {@code biz_store}）——
 * 一个门店就是一个共享娱乐空间。
 *
 * <p><b>为什么是「门店」而不是「房间」</b>：本系统的空间是共享的，
 * 平时多组顾客同时在店内各玩各的，不存在「一间房被一组人占用、
 * 别人进不来」的语义；而真实的扩张路径是开分店。详见建表脚本中的表注释。
 *
 * <p><b>本模块的三个实体与准入模型一一对应</b>：
 * <ul>
 *   <li>{@code Store} —— 门店本身，只有名称与地址，<b>不含任何状态位</b></li>
 *   <li>{@code Closure} —— 某段时间不对外营业，区间内拒绝新下单</li>
 *   <li>{@code Booking} —— 某段时间被包场，区间内仅包场人与被邀请者可进</li>
 * </ul>
 *
 * <p>后两者都是<b>时间维度</b>的准入规则，不压成门店的状态字段 ——
 * 压成状态位就表达不了「明天 10:00–14:00 维护」这种提前安排。
 * 判断顺序是「停业 → 包场 → 普通」，入口见 {@code StoreService#getStoreStatus()}。
 *
 * <p>包场的<b>收款</b>不在这里，属于模块 8（订单与支付）——
 * 本模块只负责排期，创建出来的包场处于「待付款」状态。
 */
